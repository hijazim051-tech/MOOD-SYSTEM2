create table if not exists public.stock_transfers (
  id uuid primary key default gen_random_uuid(),
  transfer_number text not null unique default ('TR-' || to_char(now(),'YYYYMMDDHH24MISS') || '-' || substr(gen_random_uuid()::text,1,4)),
  from_branch_id uuid not null references public.branches(id),
  to_branch_id uuid not null references public.branches(id),
  status text not null default 'pending' check (status in ('pending','approved','rejected','completed')),
  notes text not null default '',
  requested_by uuid null references public.user_profiles(id) on delete set null,
  approved_by uuid null references public.user_profiles(id) on delete set null,
  requested_at timestamptz not null default now(),
  approved_at timestamptz null,
  completed_at timestamptz null,
  check (from_branch_id <> to_branch_id)
);

create table if not exists public.stock_transfer_items (
  id uuid primary key default gen_random_uuid(),
  transfer_id uuid not null references public.stock_transfers(id) on delete cascade,
  product_detail_id bigint not null references public.product_details(id),
  quantity numeric not null check (quantity > 0)
);

