alter table public.customers add column if not exists rating int not null default 0;
alter table public.customers add column if not exists notes text not null default '';
alter table public.customers add column if not exists loyalty_points numeric not null default 0;
alter table public.customers add column if not exists marketing_opt_in boolean not null default false;
alter table public.customers add column if not exists last_contact_at timestamptz null;
alter table public.customers add column if not exists created_at timestamptz not null default now();
alter table public.customers add column if not exists updated_at timestamptz not null default now();

create unique index if not exists customers_phone_unique_nonempty
  on public.customers(phone)
  where btrim(phone) <> '';

insert into public.customers(name, phone, last_contact_at)
select
  coalesce(nullif(btrim(o.customer_name), ''), 'عميل غير مسجل'),
  btrim(o.customer_phone),
  max(coalesce(o.created_at, now()))
from public.orders o
where btrim(coalesce(o.customer_phone, '')) <> ''
group by btrim(o.customer_phone), coalesce(nullif(btrim(o.customer_name), ''), 'عميل غير مسجل')
on conflict (phone) where btrim(phone) <> '' do update
set name = excluded.name,
    last_contact_at = greatest(public.customers.last_contact_at, excluded.last_contact_at),
    updated_at = now();

create or replace function public.sync_customer_from_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if btrim(coalesce(new.customer_phone, '')) <> '' then
    insert into public.customers(name, phone, last_contact_at, updated_at)
    values (
      coalesce(nullif(btrim(new.customer_name), ''), 'عميل غير مسجل'),
      btrim(new.customer_phone),
      coalesce(new.created_at, now()),
      now()
    )
    on conflict (phone) where btrim(phone) <> '' do update
    set name = excluded.name,
        last_contact_at = greatest(public.customers.last_contact_at, excluded.last_contact_at),
        updated_at = now();
  end if;
  return new;
end;
$$;

drop trigger if exists orders_sync_customer on public.orders;
create trigger orders_sync_customer
after insert or update of customer_name, customer_phone on public.orders
for each row execute function public.sync_customer_from_order();

