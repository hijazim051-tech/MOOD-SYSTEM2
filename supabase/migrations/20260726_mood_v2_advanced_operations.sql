-- تطوير العملاء CRM والولاء
-- المنظومة القديمة كانت تحفظ بيانات العميل داخل جدول orders فقط، لذلك ننشئ جدول العملاء هنا
-- ثم ننقل إليه العملاء الحاليين ونبقيه متزامنًا تلقائيًا مع أي طلب جديد أو معدل.
create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null default '',
  phone text not null default '',
  birthday date null,
  anniversary date null,
  rating int not null default 0 check (rating between 0 and 5),
  notes text not null default '',
  loyalty_points numeric not null default 0,
  marketing_opt_in boolean not null default false,
  last_contact_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.customers add column if not exists birthday date null;
